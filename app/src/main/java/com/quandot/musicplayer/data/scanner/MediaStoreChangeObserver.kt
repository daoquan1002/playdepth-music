/**
 * MediaStoreChangeObserver — Debounced reactive `ContentObserver` for automatic incremental sync.
 *
 * @remarks
 * Watches `MediaStore.Audio.Media.EXTERNAL_CONTENT_URI` (with `notifyForDescendants = true`) and
 * storage mount/eject broadcasts, coalescing burst filesystem events (e.g., copying an album or
 * batch-editing tags) via `Flow.debounce(1500L)` so the scanner triggers a single lightweight
 * incremental delta pass once I/O settles. Filters out `selfChange` events and `/albumart`
 * thumbnail notifications to prevent feedback loops with [com.quandot.musicplayer.data.AlbumArtManager].
 *
 * @see HybridLibraryScanner
 * @see com.quandot.musicplayer.data.MusicRepository
 */
package com.quandot.musicplayer.data.scanner

// External SDK / Jetpack / third-party libraries
import android.content.BroadcastReceiver
import android.content.Context
import android.content.Intent
import android.content.IntentFilter
import android.database.ContentObserver
import android.net.Uri
import android.os.Build
import android.os.Handler
import android.os.Looper
import android.provider.MediaStore
import kotlinx.coroutines.FlowPreview
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.debounce

// ═══ Constants ═══
private const val DEFAULT_DEBOUNCE_MS = 1_500L

// ═══ Reactive MediaStore & Volume Observer ═══
class MediaStoreChangeObserver(private val context: Context) {

    /**
     * Emits a debounced signal whenever `MediaStore.Audio` changes or removable storage mounts /
     * unmounts. Collecting on `viewModelScope` keeps the observer strictly lifecycle-bound.
     */
    @OptIn(FlowPreview::class)
    fun observeChanges(debounceMs: Long = DEFAULT_DEBOUNCE_MS): Flow<Unit> = callbackFlow {
        val appContext = context.applicationContext
        val handler = Handler(Looper.getMainLooper())

        val contentObserver = object : ContentObserver(handler) {
            override fun onChange(selfChange: Boolean, uri: Uri?) {
                if (selfChange) return
                val uriText = uri?.toString().orEmpty()
                // Ignore albumart/thumbnail cache notifications generated by MediaProvider or AlbumArtManager
                if (uriText.contains("/albumart", ignoreCase = true) ||
                    uriText.contains("thumbnails", ignoreCase = true)
                ) {
                    return
                }
                trySend(Unit)
            }
        }

        val mountReceiver = object : BroadcastReceiver() {
            override fun onReceive(ctx: Context?, intent: Intent?) {
                trySend(Unit)
            }
        }

        val registeredObserver = runCatching {
            appContext.contentResolver.registerContentObserver(
                MediaStore.Audio.Media.EXTERNAL_CONTENT_URI,
                true,
                contentObserver
            )
            true
        }.getOrDefault(false)

        val mountFilter = IntentFilter().apply {
            addAction(Intent.ACTION_MEDIA_MOUNTED)
            addAction(Intent.ACTION_MEDIA_UNMOUNTED)
            addAction(Intent.ACTION_MEDIA_EJECT)
            addAction(Intent.ACTION_MEDIA_REMOVED)
            addDataScheme("file")
        }
        val registeredReceiver = runCatching {
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
                appContext.registerReceiver(mountReceiver, mountFilter, Context.RECEIVER_EXPORTED)
            } else {
                @Suppress("DEPRECATION")
                appContext.registerReceiver(mountReceiver, mountFilter)
            }
            true
        }.getOrDefault(false)

        awaitClose {
            if (registeredObserver) {
                runCatching { appContext.contentResolver.unregisterContentObserver(contentObserver) }
            }
            if (registeredReceiver) {
                runCatching { appContext.unregisterReceiver(mountReceiver) }
            }
        }
    }.debounce(debounceMs)
}
